import * as THREE from 'three';
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';
import { mergeGeometries } from 'three/examples/jsm/utils/BufferGeometryUtils.js';

/**
 * GLB asset registry. Models are authored in Blender (tools/blender/*.py) and exported to public/models/.
 *
 * CONTRACT (shared by all agents):
 *  - Units: meters. Origin at the model's feet (y = 0). Model faces +Z in three.js
 *    (= Blender -Y forward with the default glTF exporter "+Y up").
 *  - Regular enemies ~1-1.6 m tall at scale 1; gameplay scale is applied at runtime.
 *  - Materials: base colour comes from material colour (and/or COLOR_0 vertex colours).
 *    Any material whose NAME contains "glow", "emit" or "eye" (case-insensitive), or that has a non-black
 *    emissive colour, is treated as GLOW (rendered unlit + bloom). Everything else is BODY (lit PBR).
 *  - Each model is flattened to two merged geometries with a baked `color` attribute:
 *       body: position, normal, color  (lit with MeshStandardMaterial({vertexColors:true}))
 *       glow: position, normal, color  (MeshBasicMaterial({vertexColors:true}), colour pre-multiplied for bloom)
 *    This lets every model be drawn with InstancedMesh and one material per part.
 *  - Missing files are fine: getModel() returns null and callers fall back to procedural geometry.
 *  - Only files listed in public/models/manifest.json are fetched; the manifest is regenerated by
 *    `node tools/gen-model-manifest.mjs` (runs automatically on predev/prebuild).
 */
export interface ModelParts {
  body: THREE.BufferGeometry | null;
  glow: THREE.BufferGeometry | null;
  /** Bounding box height of the whole model (meters). */
  height: number;
  /** Optional named anchor points (Blender empties), e.g. "lantern", "muzzle". */
  anchors: Record<string, THREE.Vector3>;
}

/** Model names the loader tries to fetch. Append new names to the relevant list. */
export const MODEL_LIST = {
  characters: ['bearer'],
  enemies: ['shade', 'crawler', 'wisp', 'brute', 'stalker', 'spitter', 'bog', 'knight', 'stag', 'mire', 'king'],
  props: [
    'pine', 'deadtree', 'rock', 'grave', 'pillar', 'mushroom', 'reed',
    'oak', 'bush', 'flower', 'stump', 'log', 'lantern_post', 'ruin_wall', 'crystal', 'lily',
  ],
  pickups: ['oil_flask', 'chest', 'ember'],
};

const models = new Map<string, ModelParts>();
const GLOW_GAIN = 2.2;

function isGlow(mat: THREE.Material): boolean {
  const n = (mat.name || '').toLowerCase();
  if (n.includes('glow') || n.includes('emit') || n.includes('eye')) return true;
  const m = mat as THREE.MeshStandardMaterial;
  return !!m.emissive && m.emissive.getHex() !== 0 && (m.emissiveIntensity ?? 1) > 0;
}

function prepare(mesh: THREE.Mesh, mat: THREE.Material, glow: boolean): THREE.BufferGeometry {
  let g = mesh.geometry.clone();
  g.applyMatrix4(mesh.matrixWorld);
  if (g.index) g = g.toNonIndexed();
  if (!g.attributes.normal) g.computeVertexNormals();
  const n = g.attributes.position.count;
  const col = new Float32Array(n * 3);
  const m = mat as THREE.MeshStandardMaterial;
  const base = new THREE.Color(1, 1, 1);
  if (glow) {
    if (m.emissive && m.emissive.getHex() !== 0) base.copy(m.emissive).multiplyScalar(Math.max(1, m.emissiveIntensity ?? 1));
    else if (m.color) base.copy(m.color);
    base.multiplyScalar(GLOW_GAIN);
  } else if (m.color) base.copy(m.color);
  const vc = g.attributes.color as THREE.BufferAttribute | undefined;
  for (let i = 0; i < n; i++) {
    let r = base.r, gg = base.g, b = base.b;
    if (vc) {
      r *= vc.getX(i);
      gg *= vc.getY(i);
      b *= vc.getZ(i);
    }
    col[i * 3] = r;
    col[i * 3 + 1] = gg;
    col[i * 3 + 2] = b;
  }
  const out = new THREE.BufferGeometry();
  out.setAttribute('position', g.attributes.position);
  out.setAttribute('normal', g.attributes.normal);
  out.setAttribute('color', new THREE.BufferAttribute(col, 3));
  return out;
}

function flatten(root: THREE.Object3D): ModelParts {
  root.updateMatrixWorld(true);
  const body: THREE.BufferGeometry[] = [];
  const glow: THREE.BufferGeometry[] = [];
  const anchors: Record<string, THREE.Vector3> = {};
  root.traverse((o) => {
    const mesh = o as THREE.Mesh;
    if (mesh.isMesh) {
      const mats = Array.isArray(mesh.material) ? mesh.material : [mesh.material];
      if (mats.length === 1 || !mesh.geometry.groups.length) {
        const mat = mats[0];
        (isGlow(mat) ? glow : body).push(prepare(mesh, mat, isGlow(mat)));
      } else {
        for (const grp of mesh.geometry.groups) {
          const mat = mats[grp.materialIndex ?? 0];
          const sub = mesh.geometry.clone();
          sub.clearGroups();
          if (sub.index) {
            const idx = sub.index.array.slice(grp.start, grp.start + grp.count);
            sub.setIndex(Array.from(idx));
          }
          const tmp = new THREE.Mesh(sub, mat);
          tmp.matrixWorld.copy(mesh.matrixWorld);
          (isGlow(mat) ? glow : body).push(prepare(tmp, mat, isGlow(mat)));
        }
      }
    } else if (!(o as THREE.Mesh).isMesh && o !== root && o.children.length === 0) {
      anchors[o.name.toLowerCase()] = new THREE.Vector3().setFromMatrixPosition(o.matrixWorld);
    }
  });
  const b = body.length ? mergeGeometries(body) : null;
  const gl = glow.length ? mergeGeometries(glow) : null;
  const box = new THREE.Box3().setFromObject(root);
  return { body: b, glow: gl, height: box.max.y - box.min.y, anchors };
}

/** Loads every model in MODEL_LIST in parallel. Never rejects; missing files are skipped. */
export async function loadAssets(onProgress?: (frac: number) => void): Promise<void> {
  const loader = new GLTFLoader();
  let available: string[] = [];
  try {
    const res = await fetch('models/manifest.json');
    if (res.ok) available = await res.json();
  } catch {
    /* no manifest: procedural fallback everywhere */
  }
  const have = new Set(available);
  const jobs: [string, string][] = [];
  for (const [cat, names] of Object.entries(MODEL_LIST))
    for (const n of names) if (have.has(`${cat}/${n}`)) jobs.push([n, `models/${cat}/${n}.glb`]);
  if (!jobs.length) onProgress?.(1);
  let done = 0;
  await Promise.all(
    jobs.map(async ([name, url]) => {
      try {
        const gltf = await loader.loadAsync(url);
        models.set(name, flatten(gltf.scene));
      } catch {
        /* missing or invalid model: procedural fallback */
      } finally {
        done++;
        onProgress?.(done / jobs.length);
      }
    }),
  );
}

export function getModel(name: string): ModelParts | null {
  return models.get(name) ?? null;
}

export function loadedModelNames(): string[] {
  return [...models.keys()];
}
